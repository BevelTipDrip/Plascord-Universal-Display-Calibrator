# Codes MCCS defines as write only (a Get may fail or return nothing useful); ddcutil flags the same ones.
WRITE_ONLY = frozenset({0x01, 0x04, 0x05, 0x06, 0x08, 0x0A})


def mccs_name(code: int) -> str:
    """The MCCS name, 'manufacturer specific' for E0-FF, 'not defined in MCCS 2.2a' otherwise."""
    if code in MCCS_NAMES:
        return MCCS_NAMES[code]
    if 0xE0 <= code <= 0xFF:
        return "manufacturer specific"
    return "not defined in MCCS 2.2a"
